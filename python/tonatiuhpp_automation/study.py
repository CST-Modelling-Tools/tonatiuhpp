"""Reproducible multi-condition optical studies using Tonatiuh++'s existing CLI.

Scene mutations are made through the *existing* headless JavaScript scene API.
The C++ CLI remains the only ray tracer. This module changes no scientific code.
"""
from __future__ import annotations

from dataclasses import dataclass
import json
import math
from pathlib import Path
import re
from typing import Sequence

from .client import CliError, TonatiuhClient
from .optics import OpticalRequest, OpticalResult, _validate_optical, _measure_optics

_CASE_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$")
_NATIVE_SUMMARY = re.compile(
    r"^(rays_traced|elapsed_seconds|rays_per_second|worker_count|chunk_count|chunk_size):\s*"
    r"([0-9]+(?:\.[0-9]+)?)\s*$"
)
_INTEGER_STATS = {"rays_traced", "worker_count", "chunk_count", "chunk_size"}
_EXPECTED_STATS = _INTEGER_STATS | {"elapsed_seconds", "rays_per_second"}


@dataclass(frozen=True)
class FieldEdit:
    """Edit an existing Coin field using tn.SetValue(scene_url, field, value).

    Separator-kit URLs use the transform field conventions of Tonatiuh++.
    """
    node_url: str
    field_name: str
    value: str


@dataclass(frozen=True)
class StudyCase:
    """One independent optical simulation with explicit sun and RNG state.

    Degrees are the conventions of tn.ChangeSunPosition(azimuth, elevation).
    """
    name: str
    azimuth_deg: float
    elevation_deg: float
    rays: int
    seed: int
    update_trackers: bool = True
    field_edits: tuple[FieldEdit, ...] = ()
    export_photons: bool = False
    optical: OpticalRequest | None = None


@dataclass(frozen=True)
class StudyResult:
    case: StudyCase
    directory: Path
    prepared_scene: Path
    execution_stats: dict[str, int | float]
    photon_directory: Path | None
    stdout_file: Path
    stderr_file: Path
    result_json: Path
    optical: OpticalResult | None = None
    status_json: Path | None = None


class StudyError(RuntimeError):
    """A study could not be safely configured or completed."""


def _validate_case(case: StudyCase) -> None:
    if not isinstance(case, StudyCase):
        raise TypeError("cases must contain StudyCase objects")
    if not _CASE_NAME.fullmatch(case.name):
        raise ValueError("case name must use 1-64 ASCII letters, digits, '-' or '_', starting with a letter or digit")
    for name, value in (("azimuth_deg", case.azimuth_deg), ("elevation_deg", case.elevation_deg)):
        if type(value) not in (int, float) or not math.isfinite(value):
            raise ValueError(f"{name} must be a finite number")
    if not (-90 <= case.elevation_deg <= 90):
        raise ValueError("elevation_deg must lie between -90 and 90")
    if type(case.rays) is not int or not (1 <= case.rays <= 2**32 - 1):
        raise ValueError("rays must be in the portable CLI range 1..2^32-1")
    if type(case.seed) is not int or not (0 <= case.seed <= 2**32 - 1):
        raise ValueError("seed must be in the portable CLI range 0..2^32-1")
    if type(case.update_trackers) is not bool or type(case.export_photons) is not bool:
        raise ValueError("tracker/export switches must be booleans")
    if case.optical is not None:
        _validate_optical(case.optical)
    if not isinstance(case.field_edits, (tuple, list)):
        raise ValueError("field_edits must be a tuple or list of FieldEdit objects")
    for edit in case.field_edits:
        if not isinstance(edit, FieldEdit) or not all(
            isinstance(s, str) and s.strip() and "\x00" not in s
            for s in (edit.node_url, edit.field_name, edit.value)
        ):
            raise ValueError("field edits require nonempty node URL, field and text value")


def _js(value: object) -> str:
    """Serialize literals, never interpolate raw user text as script source."""
    return json.dumps(value, ensure_ascii=True, allow_nan=False)


def _prepare_script(source: Path, destination: Path, metadata: Path, case: StudyCase) -> str:
    lines = [
        "// Generated by tonatiuhpp_automation; uses the existing headless scene API.",
        '"use strict";',
        f"if (!tn.loadScene({_js(str(source))})) throw new Error('scene load failed');",
        f"tn.ChangeSunPosition({_js(case.azimuth_deg)}, {_js(case.elevation_deg)});",
    ]
    if not isinstance(case.field_edits, (tuple, list)):
        raise ValueError("field_edits must be a tuple or list of FieldEdit objects")
    for edit in case.field_edits:
        lines.append(
            f"tn.SetValue({_js(edit.node_url)}, {_js(edit.field_name)}, {_js(edit.value)});"
        )
    lines.extend([
        f"if (!tn.saveScene({_js(str(destination))})) throw new Error('scene save failed');",
        f"if (!tn.writeJson({_js(str(metadata))}, " + _js({
            "schema": "tonatiuhpp.python.scene-preparation.v1",
            "source_scene": str(source),
            "prepared_scene": str(destination),
            "sun_azimuth_deg": case.azimuth_deg,
            "sun_elevation_deg": case.elevation_deg,
            "field_edits": [
                {"node_url": e.node_url, "field_name": e.field_name, "value": e.value}
                for e in case.field_edits
            ],
        }) + ")) throw new Error('preparation metadata write failed');",
    ])
    return "\n".join(lines) + "\n"


def _summary(stdout: str, rays: int) -> dict[str, int | float]:
    """Parse only known CLI execution counters, never infer optical power/flux."""
    stats: dict[str, int | float] = {}
    for line in stdout.splitlines():
        match = _NATIVE_SUMMARY.fullmatch(line.strip())
        if match:
            key, raw = match.groups()
            if key in stats:
                raise StudyError(f"duplicate CLI summary field: {key}")
            if key in _INTEGER_STATS:
                if "." in raw:
                    raise StudyError(f"non-integer CLI counter: {key}")
                stats[key] = int(raw)
            else:
                stats[key] = float(raw)
    if "Trace completed." not in stdout or set(stats) != _EXPECTED_STATS:
        raise StudyError("the CLI did not return a complete recognized trace summary")
    if any(stats[key] < 0 for key in stats):
        raise StudyError("CLI reported a negative execution counter")
    if not all(math.isfinite(stats[key]) for key in ("elapsed_seconds", "rays_per_second")):
        raise StudyError("CLI reported non-finite timing statistics")
    if stats["worker_count"] < 1 or stats["chunk_count"] < 1 or stats["chunk_size"] < 1:
        raise StudyError("CLI reported invalid execution configuration")
    if stats["rays_traced"] != rays:
        raise StudyError("CLI reported a different ray count than requested")
    return stats


def _write_json(path: Path, record: dict) -> None:
    # All output directories are newly created; never replace user-supplied files.
    path.write_text(json.dumps(record, indent=2, allow_nan=False) + "\n", encoding="utf-8")


def _capture_native_error(folder: Path, stage: str, error: Exception) -> None:
    # CliError preserves the completed process's stdout/stderr on nonzero exit.
    # Timeout failures have no completed CliResult, but the exception remains.
    result = getattr(error, "result", None)
    if result is None:
        return
    (folder / f"{stage}_stdout.txt").write_text(result.stdout, encoding="utf-8")
    (folder / f"{stage}_stderr.txt").write_text(result.stderr, encoding="utf-8")


def run_study(client: TonatiuhClient, source_scene: str | Path,
              cases: Sequence[StudyCase], output_directory: str | Path,
              *, timeout: float | None = None) -> tuple[StudyResult, ...]:
    """Execute independent study cases into a *new* output directory.

    Each case starts from the same input scene.  Existing output files are never
    overwritten.  A failed case leaves its diagnostics for inspection.
    """
    source = Path(source_scene).expanduser().resolve()
    if not source.is_file() or source.suffix.lower() != ".tnhpp":
        raise FileNotFoundError(f"input .tnhpp scene was not found: {source}")
    cases = tuple(cases)
    if not cases:
        raise ValueError("at least one StudyCase is required")
    for case in cases:
        _validate_case(case)
    names = [c.name for c in cases]
    if len(set(names)) != len(names):
        raise ValueError("study case names must be unique")
    destination = Path(output_directory).expanduser().resolve()
    # Do not destroy existing results or allow the original scene inside an
    # existing study folder to be replaced by a later study.
    if destination.exists():
        raise FileExistsError(f"study output directory already exists: {destination}")
    if not destination.parent.is_dir():
        raise NotADirectoryError(f"study output parent must exist: {destination.parent}")
    destination.mkdir()

    results: list[StudyResult] = []
    for case in cases:
        folder = destination / case.name
        folder.mkdir()
        status_file = folder / "case_status.json"
        stage = "prepare"
        _write_json(status_file, {"schema": "tonatiuhpp.python.case-status.v1",
                                  "case": case.name, "status": "running", "stage": stage})
        try:
            prepared = folder / "prepared_scene.tnhpp"
            prep_script = folder / "prepare_scene.tnhpps"
            metadata = folder / "scene_preparation.json"
            prep_script.write_text(_prepare_script(source, prepared, metadata, case), encoding="utf-8")
            client.run_script(prep_script, timeout=timeout)
            if not prepared.is_file() or not metadata.is_file():
                raise StudyError(f"scene preparation did not produce its expected artifacts: {case.name}")
            config = json.loads(metadata.read_text(encoding="utf-8"))
            if config.get("schema") != "tonatiuhpp.python.scene-preparation.v1":
                raise StudyError(f"unexpected scene-preparation metadata: {case.name}")

            stage = "trace"
            _write_json(status_file, {"schema": "tonatiuhpp.python.case-status.v1",
                                      "case": case.name, "status": "running", "stage": stage})
            photons = folder / "photons" if case.export_photons else None
            if photons is not None:
                photons.mkdir()
            result = client.trace_scene(
                prepared, rays=case.rays, seed=case.seed,
                update_trackers=case.update_trackers,
                photon_export_dir=photons, timeout=timeout,
            )
            stdout_file = folder / "trace_stdout.txt"
            stderr_file = folder / "trace_stderr.txt"
            stdout_file.write_text(result.stdout, encoding="utf-8")
            stderr_file.write_text(result.stderr, encoding="utf-8")
            stats = _summary(result.stdout, case.rays)
            result_json = folder / "trace_result.json"
            _write_json(result_json, {
                "schema": "tonatiuhpp.python.trace-execution.v1",
                "source_scene": str(source), "prepared_scene": str(prepared),
                "case": case.name, "rays": case.rays, "seed": case.seed,
                "update_trackers": case.update_trackers,
                "photon_directory": str(photons) if photons is not None else None,
                "execution_stats": stats,
                "warning": "These are CLI execution counters, not optical interception or flux results.",
            })

            stage = "optics"
            if case.optical is not None:
                _write_json(status_file, {"schema": "tonatiuhpp.python.case-status.v1",
                                          "case": case.name, "status": "running", "stage": stage})
            optical = (_measure_optics(client, prepared, folder, case.optical, case.seed, timeout)
                       if case.optical is not None else None)
            _write_json(status_file, {"schema": "tonatiuhpp.python.case-status.v1",
                                      "case": case.name, "status": "completed", "stage": "complete"})
            results.append(StudyResult(case, folder, prepared, stats, photons,
                                       stdout_file, stderr_file, result_json, optical, status_file))
        except Exception as error:
            _capture_native_error(folder, stage, error)
            _write_json(status_file, {"schema": "tonatiuhpp.python.case-status.v1",
                                      "case": case.name, "status": "failed", "stage": stage,
                                      "error_type": type(error).__name__, "error": str(error)})
            raise
    return tuple(results)
